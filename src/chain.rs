use crate::table::Table;

/// Netfilter hook at which a nftables base chain is attached.
///
/// ##### Example
///
/// ```
/// use nftables_nl::chain::ChainHook;
///
/// assert_eq!(ChainHook::PRE_ROUTING.as_raw(), 0);
/// assert_eq!(ChainHook::INGRESS.as_raw(), 0);
/// ```
/// Hook numbers come from the Linux Netfilter UAPI:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter.h>
///
/// nftables encodes the hook number in the `NFTA_HOOK_HOOKNUM`
/// Netlink attribute as an `NLA_U32`:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter/nf_tables.h>
///
/// The interpretation of a hook number depends on the table's Netfilter
/// family. For example, hook value `0` is `NF_INET_PRE_ROUTING` for the
/// inet/IP families, but `NF_NETDEV_INGRESS` for the netdev family.
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ChainHook(u32);

impl ChainHook {
    /// Before routing.
    pub const PRE_ROUTING: Self = Self(0);
    /// Destined for the local system.
    pub const INPUT: Self = Self(1);
    /// Forwarded through the system.
    pub const FORWARD: Self = Self(2);
    /// Generated by the local system.
    pub const OUTPUT: Self = Self(3);
    /// After routing, before leaving the system.
    pub const POST_ROUTING: Self = Self(4);

    /// Device ingress for the INET family (`NF_INET_INGRESS`).
    pub const INET_INGRESS: Self = Self(5);

    /// Device ingress (`NETDEV` family).
    pub const INGRESS: Self = Self(0);
    /// Device egress (`NETDEV` family).
    pub const EGRESS: Self = Self(1);

    /// Returns the raw Linux Netfilter hook number.
    pub const fn as_raw(&self) -> u32 {
        self.0
    }
}

/// Priority of a nftables base chain relative to other Netfilter hooks.
/// See docs: <https://wiki.nftables.org/wiki-nftables/index.php/Configuring_chains#Base_chain_priority>
/// ##### Example
/// ```
/// use nftables_nl::chain::ChainPriority;
///
/// assert!(ChainPriority::RAW.as_raw() < ChainPriority::FILTER.as_raw());
/// ```
/// These values come from the Linux Netfilter IPv4 UAPI:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter_ipv4.h>
///
/// nftables encodes the priority in the `NFTA_HOOK_PRIORITY`
/// Netlink attribute:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter/nf_tables.h>
///
/// Lower numeric values run earlier; higher values run later.
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ChainPriority(i32);

impl ChainPriority {
    pub const FIRST: Self = Self(i32::MIN);

    /// Connection-tracking defragmentation (`NF_IP_PRI_CONNTRACK_DEFRAG`).
    pub const CONNTRACK_DEFRAG: Self = Self(-400);

    /// Raw table priority (`NF_IP_PRI_RAW`).
    pub const RAW: Self = Self(-300);

    /// SELinux processing before connection tracking (`NF_IP_PRI_SELINUX_FIRST`).
    pub const SELINUX_FIRST: Self = Self(-225);

    /// Connection tracking (`NF_IP_PRI_CONNTRACK`).
    pub const CONNTRACK: Self = Self(-200);

    /// Packet mangling (`NF_IP_PRI_MANGLE`).
    pub const MANGLE: Self = Self(-150);

    /// Destination NAT (`NF_IP_PRI_NAT_DST`).
    pub const NAT_DEST: Self = Self(-100);

    /// Normal filtering (`NF_IP_PRI_FILTER`).
    pub const FILTER: Self = Self(0);

    /// Security processing (`NF_IP_PRI_SECURITY`).
    pub const SECURITY: Self = Self(50);

    /// Source NAT (`NF_IP_PRI_NAT_SRC`).
    pub const NAT_SOURCE: Self = Self(100);

    /// SELinux processing after filtering (`NF_IP_PRI_SELINUX_LAST`).
    pub const SELINUX_LAST: Self = Self(225);

    /// Connection-tracking helper (`NF_IP_PRI_CONNTRACK_HELPER`).
    pub const CONNTRACK_HELPER: Self = Self(300);

    /// Connection-tracking confirmation (`NF_IP_PRI_CONNTRACK_CONFIRM`).
    pub const CONNTRACK_CONFIRM: Self = Self(i32::MAX);

    /// Latest possible priority (`NF_IP_PRI_LAST`).
    pub const LAST: Self = Self(i32::MAX);

    /// Returns the raw signed priority value.
    pub const fn as_raw(&self) -> i32 {
        self.0
    }
}

/// Type of an nftables base chain.
///
/// See docs: <https://wiki.nftables.org/wiki-nftables/index.php/Configuring_chains#Base_chain_types>
/// The chain type is encoded in the Linux nftables UAPI using the
/// `NFTA_CHAIN_TYPE` Netlink attribute as an `NLA_NUL_STRING`.
///
/// Kernel UAPI:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter/nf_tables.h>
///
/// The kernel looks up registered chain types by their string name:
/// <https://github.com/torvalds/linux/blob/master/net/netfilter/nf_tables_api.c>
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ChainType(&'static str);

impl ChainType {
    /// Standard packet filtering chain type.
    pub const FILTER: Self = Self("filter");

    /// Routing chain type.
    pub const ROUTE: Self = Self("route");

    /// Network address translation chain type.
    pub const NAT: Self = Self("nat");

    /// Returns the chain type name expected by the Linux nftables UAPI.
    pub const fn as_str(&self) -> &'static str {
        self.0
    }
}

/// Default policy applied by an nftables base chain.
///
/// The policy is encoded in the `NFTA_CHAIN_POLICY` Netlink attribute
/// as an `NLA_U32`.
///
/// Kernel UAPI:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter/nf_tables.h>
///
/// The values correspond to Netfilter verdicts:
/// <https://github.com/torvalds/linux/blob/master/include/uapi/linux/netfilter.h>
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ChainPolicy(u32);

impl ChainPolicy {
    /// Drop packets that reach the end of the chain without another verdict.
    /// (`NF_DROP`)
    pub const DROP: Self = Self(0);

    /// Accept packets that reach the end of the chain without another verdict.
    /// (`NF_ACCEPT`)
    pub const ACCEPT: Self = Self(1);

    /// Returns the raw Netfilter verdict value.
    pub const fn as_raw(&self) -> u32 {
        self.0
    }
}
/// An nftables chain
///
/// A base chain is attached to a Netfilter hook and supplies a hook number,
/// priority, and chain type together. It may also specify a policy and a device
/// where supported. A regular chain omits all five options and can be entered
/// through a jump or goto rule from another chain in the same table.
///
/// ##### Example
/// ```
/// use nftables_nl::chain::{Chain, ChainHook, ChainPolicy, ChainPriority, ChainType};
/// use nftables_nl::table::{Table, TableFamily, TableFlags};
///
/// let table = Table::new("filter", TableFamily::INET)
///     .with_flags(TableFlags::DORMANT);
///
/// let chain = Chain::base(
///     "input",
///     &table,
///     ChainHook::INPUT,
///     ChainPriority::FILTER,
///     ChainType::FILTER,
/// ).with_policy(ChainPolicy::ACCEPT);
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Chain {
    pub name: String,
    pub table: Table,
    pub hooknum: Option<ChainHook>,
    pub priority: Option<ChainPriority>,
    pub chain_type: Option<ChainType>,
    pub policy: Option<ChainPolicy>,
    pub device: Option<String>,
}

impl Chain {
    /// Describes a regular chain with no hook, priority, type, policy, or device.
    ///
    /// The table is cloned into the chain, so the chain does not borrow it.
    /// No kernel I/O is performed. The table must already exist or be queued
    /// earlier in the same batch when this chain is added.
    ///
    /// ```
    /// use nftables_nl::chain::Chain;
    /// use nftables_nl::{Table, TableFamily};
    ///
    /// let table = Table::new("filter", TableFamily::INET);
    /// let chain = Chain::new("services", &table);
    /// assert_eq!(chain.name, "services");
    /// assert!(chain.hooknum.is_none());
    /// ```
    pub fn new(name: impl Into<String>, table: &Table) -> Self {
        Self {
            name: name.into(),
            table: table.clone(),
            hooknum: None,
            priority: None,
            chain_type: None,
            policy: None,
            device: None,
        }
    }

    /// Describes a base chain with its required hook, priority, and type.
    ///
    /// Policy and device are omitted. The kernel defaults an omitted policy
    /// to accept. Use [`with_policy`](Self::with_policy) or
    /// [`with_device`](Self::with_device) to configure them explicitly.
    /// Construction performs no I/O. Options are validated when the chain is
    /// queued with `Batch::add_chain`, with kernel-specific checks at commit.
    ///
    /// ```
    /// use nftables_nl::chain::{Chain, ChainHook, ChainPriority, ChainType};
    /// use nftables_nl::{Table, TableFamily};
    ///
    /// let table = Table::new("filter", TableFamily::INET);
    /// let chain = Chain::base(
    ///     "input", &table, ChainHook::INPUT,
    ///     ChainPriority::FILTER, ChainType::FILTER,
    /// );
    /// assert_eq!(chain.hooknum, Some(ChainHook::INPUT));
    /// ```
    pub fn base(
        name: impl Into<String>,
        table: &Table,
        hook: ChainHook,
        priority: ChainPriority,
        chain_type: ChainType,
    ) -> Self {
        Self {
            hooknum: Some(hook),
            priority: Some(priority),
            chain_type: Some(chain_type),
            ..Self::new(name, table)
        }
    }

    /// Sets the base-chain policy, replacing any previously selected policy.
    ///
    /// Setting a policy on a regular chain is rejected by `Batch::add_chain`.
    #[must_use]
    pub fn with_policy(mut self, policy: ChainPolicy) -> Self {
        self.policy = Some(policy);
        self
    }

    /// Sets the base-chain device, replacing any previously selected device.
    ///
    /// The name and its compatibility with the family and hook are validated
    /// by `Batch::add_chain`.
    #[must_use]
    pub fn with_device(mut self, device: impl Into<String>) -> Self {
        self.device = Some(device.into());
        self
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{TableFamily, TableFlags};

    #[test]
    fn chain_new_sets_regular_chain_defaults() {
        let table = Table::new("filter", TableFamily::INET).with_flags(TableFlags::DORMANT);
        let chain = Chain::new("services", &table);
        assert_eq!(chain.name, "services");
        assert_eq!(chain.table, table);
        assert_eq!(chain.hooknum, None);
        assert_eq!(chain.priority, None);
        assert_eq!(chain.chain_type, None);
        assert_eq!(chain.policy, None);
        assert_eq!(chain.device, None);
    }

    #[test]
    fn chain_new_owns_an_independent_table_after_parent_is_dropped() {
        let chain = {
            let mut table = Table::new("filter", TableFamily::IPV6);
            let chain = Chain::new(String::from("services"), &table);
            table.name = "changed".into();
            table.flags = TableFlags::DORMANT;
            chain
        };
        assert_eq!(chain.name, "services");
        assert_eq!(chain.table.name, "filter");
        assert_eq!(chain.table.family, TableFamily::IPV6);
        assert_eq!(chain.table.flags.as_raw(), 0);
    }

    #[test]
    fn chain_base_sets_required_options_and_omits_policy_and_device() {
        let table = Table::new("filter", TableFamily::INET);
        let chain = Chain::base("input", &table, ChainHook::INPUT, ChainPriority::RAW, ChainType::FILTER);
        assert_eq!(chain.name, "input");
        assert_eq!(chain.table, table);
        assert_eq!(chain.hooknum, Some(ChainHook::INPUT));
        assert_eq!(chain.priority, Some(ChainPriority::RAW));
        assert_eq!(chain.chain_type, Some(ChainType::FILTER));
        assert_eq!(chain.policy, None);
        assert_eq!(chain.device, None);
    }

    #[test]
    fn chain_with_policy_and_device_replace_options_and_preserve_base_settings() {
        let table = Table::new("netdev_filter", TableFamily::NETDEV);
        let chain = Chain::base(
            "ingress",
            &table,
            ChainHook::INGRESS,
            ChainPriority::FILTER,
            ChainType::FILTER,
        )
        .with_policy(ChainPolicy::ACCEPT)
        .with_device("eth0")
        .with_policy(ChainPolicy::DROP)
        .with_device(String::from("eth1"));
        assert_eq!(chain.policy, Some(ChainPolicy::DROP));
        assert_eq!(chain.device.as_deref(), Some("eth1"));
        assert_eq!(chain.name, "ingress");
        assert_eq!(chain.table, table);
        assert_eq!(chain.hooknum, Some(ChainHook::INGRESS));
        assert_eq!(chain.priority, Some(ChainPriority::FILTER));
        assert_eq!(chain.chain_type, Some(ChainType::FILTER));
    }
}
